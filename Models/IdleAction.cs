namespace ParrotPet.Models;

/// <summary>Действия попугая в покое — по реальному поведению волнистых попугайчиков.</summary>
public enum IdleAction
{
    None,
    /// <summary>Чистка крыла и спинки: голова заворачивается назад, клюв перебирает перья.</summary>
    PreenWing,
    /// <summary>Чистка грудки: голова опускается, клюв перебирает пух.</summary>
    PreenChest,
    /// <summary>Чистка хвоста и огузка: хвост поднят, голова тянется назад.</summary>
    PreenTail,
    /// <summary>Встряхивание: взъерошился, дрожь, перья снова улеглись.</summary>
    Fluff,
    /// <summary>Потягивание: крыло и лапка одной стороны вытягиваются назад.</summary>
    Stretch,
    /// <summary>Зевок: клюв широко открывается, глаза щурятся.</summary>
    Yawn,
    /// <summary>Скрип клювом: признак довольного, расслабленного попугая.</summary>
    BeakGrind,
    /// <summary>Дрёма: взъерошен, глаза закрываются, одна лапка подобрана в перья.</summary>
    Doze,
    /// <summary>Чириканье: клюв открывается в такт, голова покачивается.</summary>
    Chirp,
    /// <summary>Виляние хвостом (обычно после чистки).</summary>
    TailWag,
    /// <summary>Любопытно осматривается: быстрые повороты и кивки головой.</summary>
    LookAround
}
